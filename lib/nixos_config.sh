  services.pipewire = {
    enable = true;
    alsa.enable = true;
    alsa.support32Bit = true;
    pulse.enable = true;
    wireplumber.enable = true;
  };
NIX

    echo ""
}

_nix_packages() {
    cat << 'NIX'
  # --- System packages ---
  environment.systemPackages = with pkgs; [
    # Core tools
    vim
    wget
    curl
    git
    htop
    unzip
    file
    pciutils
    usbutils
NIX

    # Hyprland ecosystem packages
    if [[ "${ENABLE_HYPRLAND:-no}" == "yes" ]]; then
        cat << 'NIX'
    # Hyprland ecosystem
    hyprpaper
    hypridle
    hyprlock
    waybar
    wofi
    mako
    grim
    slurp
    wl-clipboard
    brightnessctl
NIX
    fi

    # Desktop extras
    local extras="${DESKTOP_EXTRAS:-}"
    if [[ -n "${extras}" ]]; then
        local pkg
        local cleaned
        cleaned=$(echo "${extras}" | tr -d '"')
        for pkg in ${cleaned}; do
            echo "    ${pkg}"
        done
    fi

    # Extra packages from user
    if [[ -n "${EXTRA_PACKAGES:-}" ]]; then
        local pkg
        for pkg in ${EXTRA_PACKAGES}; do
            echo "    ${pkg}"
        done
    fi

    cat << 'NIX'
  ];
NIX

    if [[ "${ENABLE_FLATPAK:-no}" == "yes" ]]; then
        cat << 'NIX'

  # Flatpak
  services.flatpak.enable = true;
NIX
    fi

    echo ""
}

